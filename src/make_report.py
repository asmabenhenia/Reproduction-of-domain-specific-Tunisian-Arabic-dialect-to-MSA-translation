"""
make_report.py -- builds report/results_tables.md from whatever is in results/ (paper Tables 6, 7, 8, 10, 12, 13)
and runs paired-bootstrap significance tests between the main systems.

    python -m src.make_report            # missing runs are shown as "not run yet"
"""
import glob
import json
import os
import re

from src import stats

PAPER = {
    "t6": {"allam7b": (24.04, 27.83, 87.71, 23.24, 3.33), "llama3_8b": (5.42, 15.59, 799.83, 8.62, 0.00),
           "mistral7b": (9.73, 20.93, 376.71, 13.13, 0.00)},
    "t7": {"arat5v2": (79.78, 74.96, 25.32, 79.85, 31.78), "arabart": (74.79, 69.39, 31.11, 74.86, 23.56)},
    "t8": {("allam7b", 2): (80.67, 75.98, 26.33, 79.55, 32.22), ("allam7b", 3): (79.88, 75.59, 27.59, 79.33, 31.11),
           ("allam7b", 1): (77.77, 72.89, 30.60, 76.35, 25.11), ("llama3_8b", 4): (76.05, 70.71, 32.04, 74.95, 25.56),
           ("llama3_8b", 2): (76.26, 70.07, 32.41, 74.37, 23.56), ("llama3_8b", 1): (76.07, 69.80, 31.87, 74.34, 24.44),
           ("mistral7b", 2): (75.35, 69.15, 32.77, 74.24, 25.33), ("mistral7b", 1): (73.18, 66.60, 35.64, 71.74, 21.11)},
    "t12": {"ALLaM-7B C2": (0.9382, 0.6125, 0.7901), "AraT5v2": (0.9293, 0.6137, 0.7830), "AraBART": (0.8487, 0.5452, 0.6241)},
}
KEYS = ("bleu_char", "chrf_pp", "ter", "token_f1_set", "exact_match")


def load_runs():
    runs = {}
    for f in sorted(glob.glob("results/*/*/metrics.json")):
        d = os.path.dirname(f)
        if "_dryrun" in d:
            continue
        r = json.load(open(f, encoding="utf-8"))
        name = os.path.basename(d)
        neural = os.path.join(d, "neural_metrics.json")
        runs[name] = {"dir": d, "m": r["metrics"], "meta": r.get("meta", {}),
                      "neural": json.load(open(neural, encoding="utf-8")) if os.path.exists(neural) else None}
    return runs


def row(label, m, paper=None):
    cells = " | ".join(f"{m[k]:.2f}" for k in KEYS)
    pap = " | ".join(f"{v:.2f}" for v in paper) if paper else "n/a | n/a | n/a | n/a | n/a"
    return f"| {label} | {cells} | {pap} |"


HEAD = ("| run | BLEU | chrF++ | TER | TokF1 | EM | paper BLEU | paper chrF++ | paper TER | paper TokF1 | paper EM |\n"
        "|---|---|---|---|---|---|---|---|---|---|---|")


def lora_key(name):
    m = re.match(r"lora_(allam7b|llama3_8b|mistral7b)_c(\d)_seed(\d+)(.*)", name)
    return (m.group(1), int(m.group(2)), int(m.group(3)), m.group(4)) if m else None


def pairwise(runs, a, b, n=1000):
    ra = [json.loads(l) for l in open(os.path.join(runs[a]["dir"], "predictions.jsonl"), encoding="utf-8")]
    rb = [json.loads(l) for l in open(os.path.join(runs[b]["dir"], "predictions.jsonl"), encoding="utf-8")]
    refs = [x["reference"] for x in ra]
    pa, pb = [x["prediction"] for x in ra], [x["prediction"] for x in rb]
    r = stats.paired_bootstrap_bleu(pa, pb, refs, n=n)
    from src.metrics import exact_match
    ea = [exact_match(p, t) for p, t in zip(pa, refs)]; eb = [exact_match(p, t) for p, t in zip(pb, refs)]
    only_a = sum(x and not y for x, y in zip(ea, eb)); only_b = sum(y and not x for x, y in zip(ea, eb))
    sig = "significant" if (r["ci95"][0] > 0 or r["ci95"][1] < 0) else "NOT significant"
    return (f"| {a} vs {b} | {r['obs_a']:.2f} vs {r['obs_b']:.2f} | {r['diff']:+.2f} | [{r['ci95'][0]:+.2f}, {r['ci95'][1]:+.2f}] "
            f"| {r['pct_a_better']:.1f}% | {sig} | {only_a} / {only_b} |")


def main():
    runs = load_runs()
    out = ["# Results tables (generated by `python -m src.make_report`)\n",
           "Columns after `EM` are the paper's values. Test set: the same 450 sentences everywhere.\n"]

    out += ["## Table 6 - zero-shot", HEAD]
    for k, p in PAPER["t6"].items():
        n = f"zeroshot_{k}"
        out.append(row(n, runs[n]["m"], p) if n in runs else f"| {n} | not run yet | | | | | " + " | ".join(f"{v:.2f}" for v in p) + " |")

    out += ["", "## Table 7 - Seq2Seq (every run we have)", HEAD]
    for n, r in runs.items():
        if n.startswith("seq2seq_"):
            key = "arat5v2" if "arat5v2" in n else "arabart"
            ck = os.path.basename(r["meta"].get("best_checkpoint") or "-")
            paper = PAPER["t7"][key] if ("lr0.0005" in n and "bf16w" not in n) else None
            out.append(row(f"{n} ({ck})", r["m"], paper))

    out += ["", "## Table 8 - LoRA (seed 42, greedy)", HEAD]
    for (mdl, cfg), p in PAPER["t8"].items():
        n = f"lora_{mdl}_c{cfg}_seed42"
        r = runs.get(n)
        if r:
            out.append(row(f"{n} (r={r['meta'].get('r')}, trainable {r['meta'].get('trainable_pct')}%, stopped early: {r['meta'].get('stopped_early')})", r["m"], p))
        else:
            out.append(f"| {n} | not run yet | | | | | " + " | ".join(f"{v:.2f}" for v in p) + " |")
    extra = [n for n in runs if n.startswith("lora_") and lora_key(n) and (lora_key(n)[2] != 42 or lora_key(n)[3])]
    for n in extra:
        out.append(row(n + " (variant)", runs[n]["m"]))

    out += ["", "## Table 10 - best system per paradigm (by BLEU)", "| paradigm | ours | BLEU | paper | paper BLEU |", "|---|---|---|---|---|"]
    for title, prefix, pap in (("zero-shot", "zeroshot_", ("ALLaM-7B (no FT)", 24.04)), ("Seq2Seq FT", "seq2seq_", ("AraT5v2", 79.78)),
                               ("LoRA FT", "lora_", ("ALLaM-7B Config 2", 80.67))):
        c = [(r["m"]["bleu_char"], n) for n, r in runs.items() if n.startswith(prefix)]
        out.append(f"| {title} | {max(c)[1]} | {max(c)[0]:.2f} | {pap[0]} | {pap[1]} |" if c else f"| {title} | not run yet | | {pap[0]} | {pap[1]} |")

    out += ["", "## Table 12 - neural metrics (COMET / COMETKiwi-DA / BLEURT)", "| run | COMET | COMETKiwi-DA | BLEURT |", "|---|---|---|---|"]
    nn = [(n, r["neural"]) for n, r in runs.items() if r["neural"]]
    for n, x in nn:
        out.append(f"| {n} | {x.get('comet')} | {x.get('cometkiwi_da')} | {x.get('bleurt')} |")
    if not nn:
        out.append("| not run yet (SESSION 5) | | | |")
    out.append("| paper: ALLaM-7B C2 / AraT5v2 / AraBART | 0.9382 / 0.9293 / 0.8487 | 0.6125 / 0.6137 / 0.5452 | 0.7901 / 0.7830 / 0.6241 |")

    out += ["", "## Table 13 - greedy vs beam search (ALLaM Config 2)", HEAD]
    g, b = runs.get("lora_allam7b_c2_seed42"), runs.get("beam4_lora_allam7b_c2")
    out.append(row("greedy (lora_allam7b_c2)", g["m"], (80.67, 75.98, 26.33, 79.55, 32.22)) if g else "| greedy | not run yet | | | | | 80.67 | 75.98 | 26.33 | 79.55 | 32.22 |")
    out.append(row("beam 4", b["m"], (69.38, 63.75, 43.26, 65.51, 6.89)) if b else "| beam 4 | not run yet | | | | | 69.38 | 63.75 | 43.26 | 65.51 | 6.89 |")

    out += ["", "## Significance: paired bootstrap on char-BLEU (1000 resamples, same 450 test sentences)",
            "'A better' = share of resamples in which A beats B. Last column: sentences exactly right only for A / only for B.",
            "| comparison | BLEU A vs B | A-B | 95% CI | A better | verdict | EM only A / only B |", "|---|---|---|---|---|---|---|"]
    ara = [n for n in runs if n.startswith("seq2seq_arabart")]
    best_ara = max(ara, key=lambda n: runs[n]["m"]["bleu_char"]) if ara else None
    t5 = next((n for n in ("seq2seq_arat5v2_lr0.0005_seed42_final", "seq2seq_arat5v2_lr0.0005_seed42") if n in runs), None)
    pairs = []
    if "lora_allam7b_c2_seed42" in runs and t5:
        pairs.append(("lora_allam7b_c2_seed42", t5))
    if "lora_allam7b_c2_seed42" in runs and best_ara:
        pairs.append(("lora_allam7b_c2_seed42", best_ara))
    if t5 and best_ara:
        pairs.append((t5, best_ara))
    for other in ("lora_llama3_8b_c2_seed42", "lora_llama3_8b_c4_seed42", "lora_mistral7b_c2_seed42"):
        if "lora_allam7b_c2_seed42" in runs and other in runs:
            pairs.append(("lora_allam7b_c2_seed42", other))
    for a, b2 in pairs:
        out.append(pairwise(runs, a, b2))
    if not pairs:
        out.append("| not enough runs yet | | | | | | |")

    os.makedirs("report", exist_ok=True)
    open("report/results_tables.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
